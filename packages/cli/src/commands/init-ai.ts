import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { aiRules, DOCS_URL, type Stack, setupGuide } from '@joralvmel/cosmos-core';

export const BLOCK_START = '<!-- cosmos-ui:start -->';
export const BLOCK_END = '<!-- cosmos-ui:end -->';
export const MCP_SERVER = 'cosmos-ui';

const packageOf: Record<Stack, string> = {
  react: '@joralvmel/cosmos-react',
  next: '@joralvmel/cosmos-react',
  angular: '@joralvmel/cosmos-angular',
  html: '@joralvmel/cosmos-elements',
  'react-native': '@joralvmel/cosmos-native',
  tailwind: '@joralvmel/cosmos-tailwind',
};

export interface InitAiOptions {
  cwd: string;
  stack: Stack;
  copilot?: boolean;
  agents?: boolean;
  claude?: boolean;
  mcp?: boolean;
  dryRun?: boolean;
}

export interface FileChange {
  path: string;
  action: 'created' | 'updated' | 'unchanged';
}

/** Marked block written into the instruction files of the consumer project. */
export function instructionsBlock(stack: Stack): string {
  const guide = setupGuide(stack);
  const pkg = packageOf[stack];
  return [
    BLOCK_START,
    `<!-- Generated by \`npx @joralvmel/cosmos-cli init-ai --stack ${stack}\`. Re-run it to update; edits inside this block are replaced. -->`,
    '',
    '## Cosmos UI',
    '',
    `This project uses [Cosmos UI](${DOCS_URL}) with ${guide.title}.`,
    '',
    `- Reference for assistants: ${DOCS_URL}llms.txt (everything: ${DOCS_URL}llms-full.txt) and \`node_modules/${pkg}/llms.md\`.`,
    `- MCP server \`${MCP_SERVER}\` (\`.vscode/mcp.json\`): \`list_components\`, \`get_component\`, \`get_setup\`, \`get_tokens\`, \`list_themes\`, \`search_docs\`. Use it before writing UI code.`,
    `- Setup guide: ${DOCS_URL}${guide.guide}`,
    '',
    '### Rules',
    '',
    ...aiRules(stack).map(rule => `- ${rule}`),
    BLOCK_END,
  ].join('\n');
}

/** Inserts or replaces the marked block, keeping everything else of the file. */
export function upsertBlock(content: string, block: string): string {
  const start = content.indexOf(BLOCK_START);
  const end = content.indexOf(BLOCK_END);
  if (start !== -1 && end > start) {
    return `${content.slice(0, start)}${block}${content.slice(end + BLOCK_END.length)}`;
  }
  return content.trim() ? `${content.replace(/\s*$/, '')}\n\n${block}\n` : `${block}\n`;
}

/** Adds the Cosmos MCP server to a VS Code `mcp.json`, keeping the other servers. */
export function mergeMcpConfig(content: string | undefined): string {
  let config: { servers?: Record<string, unknown> } & Record<string, unknown> = {};
  if (content?.trim()) {
    try {
      config = JSON.parse(content);
    } catch {
      throw new Error(
        '.vscode/mcp.json is not plain JSON (comments?); add the "cosmos-ui" server by hand or fix the file.'
      );
    }
  }
  config.servers = {
    ...config.servers,
    [MCP_SERVER]: { type: 'stdio', command: 'npx', args: ['-y', '@joralvmel/cosmos-mcp'] },
  };
  return `${JSON.stringify(config, null, 2)}\n`;
}

/** Printed after the command: install commands and setup steps of the stack. */
export function installSteps(stack: Stack): string {
  const guide = setupGuide(stack);
  const lines = [`Next steps for ${guide.title}:`];
  for (const command of guide.install) lines.push(`  $ ${command}`);
  guide.steps.forEach((step, index) => {
    lines.push(`  ${index + 1}. ${step.title}${step.file ? ` (${step.file})` : ''}`);
  });
  lines.push(`  Guide: ${DOCS_URL}${guide.guide}`);
  return lines.join('\n');
}

export function initAi(options: InitAiOptions): FileChange[] {
  const { cwd, stack, dryRun = false } = options;
  const block = instructionsBlock(stack);
  const targets: [string, (content: string | undefined) => string][] = [];
  if (options.copilot ?? true) {
    targets.push(['.github/copilot-instructions.md', content => upsertBlock(content ?? '', block)]);
  }
  if (options.agents ?? true) {
    targets.push(['AGENTS.md', content => upsertBlock(content ?? '', block)]);
  }
  if (options.claude) targets.push(['CLAUDE.md', content => upsertBlock(content ?? '', block)]);
  if (options.mcp ?? true) targets.push(['.vscode/mcp.json', mergeMcpConfig]);

  const changes: FileChange[] = [];
  const writes: [string, string][] = [];
  for (const [path, update] of targets) {
    const full = join(cwd, path);
    const current = existsSync(full) ? readFileSync(full, 'utf8') : undefined;
    const next = update(current);
    const action = current === undefined ? 'created' : current === next ? 'unchanged' : 'updated';
    changes.push({ path, action });
    if (action !== 'unchanged') writes.push([full, next]);
  }
  if (!dryRun) {
    for (const [full, content] of writes) {
      mkdirSync(dirname(full), { recursive: true });
      writeFileSync(full, content);
    }
  }
  return changes;
}
