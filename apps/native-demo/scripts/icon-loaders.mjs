// Metro requires statically analyzable individual import paths.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const catalog = JSON.parse(
  await readFile(new URL('../../../packages/icons/src/catalog.json', import.meta.url), 'utf8')
);
const lines = catalog.map(({ name }) => {
  const key = /^[a-zA-Z_$][\w$]*$/.test(name) ? name : `'${name}'`;
  const prefix = `  ${key}: () =>`;
  const expression = `import('@joralvmel/cosmos-icons/${name}'),`;
  return `${prefix}${prefix.length + 1 + expression.length > 100 ? '\n   ' : ''} ${expression}`;
});
await writeFile(
  fileURLToPath(new URL('../src/icon-loaders.ts', import.meta.url)),
  `// Generated by scripts/icon-loaders.mjs from the metadata catalog; no artwork is imported eagerly.\nexport const iconLoaders: Record<string, () => Promise<Record<string, unknown>>> = {\n${lines.join('\n')}\n};\n`
);
